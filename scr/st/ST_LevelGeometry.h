#pragma once

// Offsets in a 40-byte model entry used by the collision tests.
enum ST_LevelGeometryModelOffset {
    ST_GEOMETRY_MODEL_VERTEX_OFFSET = 0x00,
    ST_GEOMETRY_MODEL_VERTEX_COUNT = 0x04,
    ST_GEOMETRY_MODEL_VECTOR_OFFSET = 0x08,
    ST_GEOMETRY_MODEL_RECORD_OFFSET = 0x10,
    ST_GEOMETRY_MODEL_20_BYTE_RECORD_COUNT = 0x18,
    ST_GEOMETRY_MODEL_24_BYTE_RECORD_COUNT = 0x1A,
    ST_GEOMETRY_MODEL_28_BYTE_RECORD_COUNT = 0x1C,
    ST_GEOMETRY_MODEL_32_BYTE_RECORD_COUNT = 0x1E,
    ST_GEOMETRY_MODEL_THREE_VERTEX_COUNT = 0x20,
    ST_GEOMETRY_MODEL_FOUR_VERTEX_COUNT = 0x24
};

// Offsets shared by the three- and four-vertex collision records.
enum ST_LevelCollisionRecordOffset {
    ST_GEOMETRY_RECORD_FLAGS = 0x02,
    ST_GEOMETRY_RECORD_VECTOR_OFFSET = 0x04,
    ST_GEOMETRY_RECORD_VERTEX_0_OFFSET = 0x06,
    ST_GEOMETRY_RECORD_VERTEX_1_OFFSET = 0x08,
    ST_GEOMETRY_RECORD_VERTEX_2_OFFSET = 0x0A,
    ST_GEOMETRY_RECORD_VERTEX_3_OFFSET = 0x0C,
    ST_GEOMETRY_RECORD_CURSOR_OFFSET = ST_GEOMETRY_RECORD_FLAGS
};
